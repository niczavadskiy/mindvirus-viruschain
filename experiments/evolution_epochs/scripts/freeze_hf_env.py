"""Print a pip-freeze style lock of packages needed for HF smoke."""

from __future__ import annotations

import importlib.metadata as md


PACKAGES = (
    "numpy",
    "torch",
    "transformers",
    "pyyaml",
    "matplotlib",
    "accelerate",
    "safetensors",
    "tokenizers",
    "huggingface-hub",
)


def _ver(name: str) -> str:
    try:
        return md.version(name)
    except md.PackageNotFoundError:
        return "NOT_INSTALLED"


def main() -> None:
    print("# Auto-generated by scripts/freeze_hf_env.py")
    print("# Known-good mini smoke: configs/smoke_hf_mini.yaml")
    for name in PACKAGES:
        print(f"{name}=={_ver(name)}")
    for banned in ("torchaudio", "torchvision", "sentence-transformers"):
        status = _ver(banned)
        print(f"# banned {banned}: {status}")


if __name__ == "__main__":
    main()
